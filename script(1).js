  document.addEventListener("keydown", e => { if (e.key === "Escape") close(); });
  $("#languageSelect").addEventListener("change", () => { refreshBtn(); if (ov.classList.contains("open")) draw(); });
  $("#bookingForm").addEventListener("submit", () => setTimeout(refreshBtn, 0));

  renderBarbers();
  refreshBtn();
