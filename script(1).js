      $$("[data-r]", box).forEach(b => b.onclick = () => { role = b.dataset.r; draw(); });
      $("#toLogin").onclick = () => { view = "login"; draw(); };
      $("#sGo").onclick = async () => {
        const name = $("#sName").value.trim(), email = $("#sEmail").value.trim().toLowerCase(), pw = $("#sPass").value;
        if (!name || !/^\S+@\S+\.\S+$/.test(email)) return msg(a("req"));
        if (pw.length < 6) return msg(a("short"));
        const all = users();
        if (all.some(z => z.email === email)) return msg(a("exists"));
        const u = { id: "u" + Date.now().toString(36) + Math.random().toString(36).slice(2, 6), role, name, email, phone: $("#sPhone").value.trim(), pass: await hash(pw), createdAt: new Date().toISOString() };
        if (role === "barber") { u.specialty = $("#sSpec").value.trim() || a("barber"); u.city = $("#sCity").value.trim(); }
        all.push(u); saveUsers(all); localStorage.setItem(KS, u.id);
        refreshBtn(); renderBarbers(); draw();
        msg(role === "barber" ? a("visible") : a("welcome") + " " + name, true);
      };
