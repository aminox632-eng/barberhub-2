$("#bookingForm").addEventListener("submit", event => {
  event.preventDefault();

  const form = event.currentTarget;
  const message = $("#formMessage");

  message.classList.remove("error");

  if (!form.reportValidity()) {
    message.textContent = t("required");
    message.classList.add("error");
    return;
  }

  const booking = {
    name: $("#customerName").value.trim(),
    phone: $("#customerPhone").value.trim(),
    service: $("#serviceSelect").value,
    barber: $("#barberSelect").value,
    date: $("#bookingDate").value,
    time: $("#bookingTime").value,
    notes: $("#bookingNotes").value.trim(),
    createdAt: new Date().toISOString(),
    id: "b" + Date.now().toString(36),
    userId: localStorage.getItem("barberhub_session") || null
  };

  try {
    const bookings = JSON.parse(
      localStorage.getItem("barberhub_bookings") || "[]"
    );

    if (booking.barber && bookings.some(b =>
      b.barber === booking.barber && b.date === booking.date && b.time === booking.time)) {
      message.textContent = t("taken");
      message.classList.add("error");
      return;
    }

    bookings.push(booking);

    localStorage.setItem(
      "barberhub_bookings",
      JSON.stringify(bookings)
    );

    message.textContent = t("success");
    showToast(t("success"));

    form.reset();
    initDateAndTimes();

  } catch (error) {
    message.textContent = t("error");
    message.classList.add("error");
  }
});

